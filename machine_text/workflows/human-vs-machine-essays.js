export const meta = {
  name: 'human-vs-machine-essays',
  description: 'Subagents write 320 essays on the same assignments as sampled student essays; searchers find and verify references on human versus machine text',
  phases: [
    { title: 'Write essays', detail: '320 essays: two conditions, four Claude tiers, one essay per agent' },
    { title: 'Find references', detail: 'three search angles on human versus machine text' },
    { title: 'Verify references', detail: 'each reference checked against a primary record' },
  ],
}

const TIERS = ['fable', 'sonnet', 'haiku', 'opus']
const dir = args.dir
const n = args.n
const pad = i => String(i).padStart(3, '0')

// Essay writers are told nothing about the study. One essay per agent so that essays do not anchor on each other.
const essayRun = parallel(Array.from({ length: n }, (_, i) => () =>
  agent(
    `Read the JSON file ${dir}/jobs/${pad(i)}.json. It has two fields, "instructions" and "output_path". ` +
    `Do what "instructions" says and save the result as plain text at "output_path" with the Write tool. ` +
    `Use no skills and no other tools, and do not read any other file. When the file is saved, reply with the single word: done.`,
    { label: `essay ${pad(i)}`, phase: 'Write essays', model: TIERS[Math.floor(i / 2) % 4], effort: 'low' }
  )
))

const REFS = {
  type: 'object',
  properties: {
    refs: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          key: { type: 'string', description: 'citation key: first author surname in lower case plus year, e.g. guo2023' },
          authors: { type: 'string' },
          year: { type: 'string' },
          title: { type: 'string' },
          venue: { type: 'string' },
          locator: { type: 'string', description: 'DOI, arXiv id, ACL Anthology id or URL of the primary record' },
          finding: { type: 'string', description: 'one sentence: what this work reports that bears on the question' },
        },
        required: ['key', 'authors', 'year', 'title', 'locator', 'finding'],
      },
    },
  },
  required: ['refs'],
}

const ANGLES = [
  { key: 'affect', prompt: 'published measurements of how sentiment, emotion, affect, positivity or negativity differ between human-written text and text generated by large language models on the same prompts or questions (direction and size of the difference, which data, which models). Include the paper that introduced the HC3 human versus ChatGPT corpus and what it reported about emotion or sentiment.' },
  { key: 'style', prompt: 'corpora that pair human and machine text on the same prompts (HC3, PERSUADE 2.0 student essays and the essays generated for it, RAID, Ghostbuster, M4, MAGE) and published stylometric comparisons of human and LLM writing: vocabulary, grammar, rhetorical style, variability across sentences ("burstiness"), and excess use of particular words.' },
  { key: 'use', prompt: 'the reliability and the ethics of detecting machine-written text (false positives, bias against non-native writers, effect of paraphrasing), any published evidence on tools or feedback loops that revise LLM text toward human style, and published evidence of a positivity or agreeableness bias in LLM output.' },
]

const COMMON = 'Use web search, web fetch and any literature tools available (Crossref API at https://api.crossref.org/works?query.bibliographic=..., the arXiv API, ACL Anthology, DBLP, Consensus search). Report only works you have located in a primary record. Do not invent anything; leave out what you cannot locate. Put no personal information in any request. Return at most 8 references, the most relevant first.'

phase('Find references')
const found = (await parallel(ANGLES.map(a => () =>
  agent(`Find the key published references on: ${a.prompt}\n\n${COMMON}`, { label: `search: ${a.key}`, phase: 'Find references', schema: REFS })
))).filter(Boolean).flatMap(r => r.refs)

// Dedup across the three searchers before the more expensive verification (needs all results at once).
const seen = new Set()
const unique = found.filter(r => {
  const k = (r.title || '').toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 40)
  if (!k || seen.has(k)) return false
  seen.add(k)
  return true
})
log(`${found.length} references found, ${unique.length} after removing duplicates`)

const VERDICT = {
  type: 'object',
  properties: {
    key: { type: 'string' },
    verified: { type: 'boolean', description: 'true only if a primary record confirms that the work exists with these authors, title and year' },
    bibtex: { type: 'string', description: 'a complete BibTeX entry with the corrected metadata, using the given key; empty if not verified' },
    finding: { type: 'string', description: 'the relevant finding as the source itself states it, in one sentence in your own words; empty if you could not confirm it' },
    support: { type: 'string', enum: ['full text', 'abstract', 'not confirmed'] },
    note: { type: 'string', description: 'anything corrected or doubtful' },
  },
  required: ['key', 'verified', 'bibtex', 'finding', 'support'],
}

phase('Verify references')
const verified = (await parallel(unique.map(r => () =>
  agent(
    `Check this reference against a primary record (publisher page, DOI record, arXiv, ACL Anthology, DBLP or Crossref) and try to show that it is wrong. ` +
    `Reference: ${r.authors} (${r.year}). ${r.title}. ${r.venue || ''}. Locator: ${r.locator}. ` +
    `Claimed finding: ${r.finding}\n\n` +
    `1. Does the work exist with these authors, title, venue and year? Correct any detail that is wrong. If you cannot confirm it exists, set verified to false. ` +
    `2. Does the source itself support the claimed finding? Read the abstract, and the full text if it is open. Restate the finding as the source gives it; if the source does not support it, say "not confirmed" and leave the finding empty. ` +
    `3. Write a complete BibTeX entry with the key ${r.key}. Use web fetch and search; do not guess. Put no personal information in any request.`,
    { label: `verify: ${r.key}`, phase: 'Verify references', schema: VERDICT })
))).filter(Boolean)

const essays = (await essayRun)
const done = essays.filter(e => typeof e === 'string' && /done/i.test(e)).length
log(`${done} of ${n} essay agents reported done`)

return {
  essays_reported_done: done,
  essays_failed_indices: essays.map((e, i) => (typeof e === 'string' && /done/i.test(e)) ? null : i).filter(i => i !== null),
  references_found: found.length,
  references: verified,
}